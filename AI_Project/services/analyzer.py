from openai import OpenAI
import config

client = OpenAI(api_key=config.OPENAI_API_KEY)

def analyze_meeting(transcript: str) -> str:
    prompt = f"""
أنت خبير تحليل اجتماعات احترافي.

مهم جدًا:
- لا تحذف أي قسم.
- لا تختصر الإخراج.
- يجب أن تخرج كل الأقسام الثلاثة دائمًا.

قواعد صارمة:
1- استخرج عنوان مختصر واضح (3-6 كلمات).
2- اكتب ملخص تنفيذي دقيق بدون تكرار.
3- استخرج جميع المهام المهمة فقط.
4- تجاهل الكلام غير التنفيذي.
5- لكل مهمة اذكر:
   - وصف المهمة بشكل واضح
   - المسؤول (حتى لو مذكور بشكل غير مباشر)
6- إذا لم يُذكر مسؤول صراحة أو ضمنيًا اكتب: غير محدد.
7- لا تخترع مهام غير موجودة.
8- لا تكرر نفس المهمة بصياغات مختلفة.

🔥 قواعد فهم المسؤول (إضافة قوية بدون حذف):
- إذا وردت عبارات مثل:
  (تم تعيين، مسؤول عن، سيتولى، مكلف بـ، هيقوم بـ)
  يجب اعتبار الشخص المذكور هو المسؤول عن المهمة.
- استخرج المسؤول حتى لو لم يكن مذكور بصيغة مباشرة.

🔥 قواعد المهام (مهم جدًا):
- كل مهمة يجب أن تكون في سطر منفصل.
- لا تدمج أكثر من مهمة في سطر واحد.
- لا تكتب المهام داخل الملخص.
- يجب أن يكون قسم "المهام" واضح ومنفصل.
- لا تتجاهل أي مهمة حتى لو كانت ضمنية في النص.

🔥 قواعد المتحدثين (مهمة جدًا - بدون حذف):
9- قم بتحديد اسم المتحدث لكل جملة في النص.
10- إذا بدأ المتحدث باسمه (مثال: محمد:)، استخدمه.
11- إذا لم يُذكر الاسم، استنتج المتحدث من السياق.
12- حافظ على نفس المتحدث إذا استمر الكلام.
13- لا تكتب أي جملة بدون اسم متحدث قبلها.

🔥 الحضور:
- استخرج جميع أسماء المتحدثين من النص.
- اجمعهم في قائمة واحدة بدون تكرار.
- اكتبهم تحت قسم بعنوان "الحضور".
- لا تترك هذا القسم فارغًا إذا وُجدت أسماء في النص.

🚨 مهم جدًا:
- تأكد أن قسم "المهام" يحتوي على مهام فعلية وليس فارغًا إذا وُجدت مهام في النص.
- تأكد أن كل مهمة لها مسؤول واضح أو "غير محدد".

أخرج النتيجة بهذا الشكل فقط:

عنوان الاجتماع:
...

الحضور:
- اسم
- اسم

الملخص التنفيذي:
...

المهام:
- وصف المهمة — المسؤول: الاسم
- وصف المهمة — المسؤول: الاسم

النص:
...
{transcript}
"""

    response = client.chat.completions.create(
        model="gpt-4o-mini",
        messages=[
            {"role": "system", "content": "أنت خبير تحليل اجتماعات عربي."},
            {"role": "user", "content": prompt}
        ],
        temperature=0.2
    )

    return response.choices[0].message.content
